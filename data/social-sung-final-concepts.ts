// 기말고사 · 사회(성신제T): 에디션(학습지)마다 개념 정리 한 단원. 예시는 그 에디션의 객관식 카드 전부다.
const examplesFor = (topic: string) => socialSungFinalCards
  .filter(card => card.topic === topic)
  .map(card => ({ id: card.id, context: card.question, explanation: card.explanation, sourceNote: `성신제T · ${card.source?.label} · ${card.source?.page}쪽` }));

const lessonOf = (key: string, summary: string, sections: ConceptLesson['sections']): ConceptLesson => {
  const edition = socialSungFinalEditions.find(e => e.key === key);
  if (!edition) throw new Error(`No edition ${key}`);
  return {
    id: `social-sung-final-concept-${key}`, deckId: 'social-sung-final', title: `${edition.name} · ${edition.source.label}`, summary, sections,
    topicKeys: [edition.name], sourceNote: `성신제T 학습지 ${key} · ${edition.source.label}`,
    examplesLabel: '이 에디션의 문제', examples: examplesFor(edition.name),
  };
};

